
export interface SignatureMech {
    chassis: string; // catalog-resolvable chassis name (loose-match)
    note?: string;
}

export interface NotablePilot {
    name: string;
    role: string;
    gunnery?: number | null;
    piloting?: number | null;
    note?: string;
}

export interface PaintScheme {
    primary: string; // hex
    secondary?: string;
    accent?: string;
    pattern?: 'solid' | 'split' | 'bands' | 'checker' | 'stripe' | 'dazzle';
    note?: string;
    source?: string;
}

export interface FormationRecord {
    name: string;
    aliases?: string[];
    /** Owning faction — MekBay faction.name match list (canonical first). */
    faction: string[];
    foundedYear?: number | null; // null = predates all playable eras / unverified
    disbandedYear?: number | null;
    /** Short role/character tag for the picker card. */
    role: string;
    /** One original sentence, <= ~18 words. */
    blurb: string;
    signatureMechs: SignatureMech[];
    notablePilots: NotablePilot[];
    /** T-024 faction-tied logistics seam (economy tuning later, T-022). */
    logistics: 'house-mic' | 'merc-market';
    sources: string[];
    // unit insignia MIRRORED to our own infra (/images/formations/<id>.png) — the runtime app NEVER hotlinks
    // Sarna/unitcolorcompendium/Camospecs (the db.mekbay.com lesson). Both optional → the UI falls back to the
    // faction crest + heraldry colors so every command always shows something.
    paint?: PaintScheme;
    crest?: string; // e.g. '/images/formations/sword-of-light-1st.png'
    crestSource?: string; // credit: source site + artist (T-022 fan-content posture)
}

